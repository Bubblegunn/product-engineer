#!/usr/bin/env node
// One section per results directory, one directory per model: the five metrics for the bare and the
// skill arm, the per-task mean delta with its seeded bootstrap interval, and a reading fixed in advance
// by evals/MODELS-DESIGN.md. Models are never averaged together.
//
//   node evals/by-model.mjs evals/results-haiku-4-5-2026-10-21 evals/results-2026-10-17/core > evals/RESULTS-models.md
//
// No model is called. Node built-ins only.
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { metrics, score, bootstrapDelta, coreRows } from "./score.mjs";

/** "worked" when the whole interval is above zero, "worse" when it is all below, otherwise "no clear effect". */
export function reading(low, high) {
  if (low > 0) return "worked";
  if (high < 0) return "worse";
  return "no clear effect";
}

const mean = (xs) => (xs.length ? xs.reduce((s, x) => s + x, 0) / xs.length : null);

/** Per-task mean pass rate for each arm, then the mean delta and its interval, for one metric. */
export function metricRow(rows, key) {
  const tasks = [...new Set(rows.map((r) => r.task))].sort();
  const perTask = tasks.map((task) => {
    const arm = (c) => rows.filter((r) => r.task === task && r.condition === c).map((r) => (r.results[key] ? 1 : 0));
    return { bare: arm("bare"), skill: arm("skill") };
  });
  const count = (c) => rows.filter((r) => r.condition === c && r.results[key]).length;
  const runsPerTask = Math.min(...perTask.flatMap((t) => [t.bare.length, t.skill.length]));
  const row = { key, title: metrics[key].title, bare: count("bare"), skill: count("skill"), runsPerTask };
  if (runsPerTask >= 2) {
    const deltas = perTask.map((t) => mean(t.skill) - mean(t.bare));
    const ci = bootstrapDelta(deltas);
    return { ...row, delta: ci.mean, low: ci.low, high: ci.high, reading: reading(ci.low, ci.high) };
  }
  return { ...row, delta: (row.skill - row.bare) / tasks.length, low: null, high: null, reading: "not computed, one run per task" };
}

export function summarise(dir) {
  const rows = coreRows(score(resolve(dir)));
  const first = rows.find((r) => r.meta?.requested_model) ?? rows[0];
  const arm = (c) => rows.filter((r) => r.condition === c);
  const cost = (c) => mean(arm(c).map((r) => r.meta?.cost_usd).filter((x) => typeof x === "number"));
  return {
    dir,
    model: first?.meta?.requested_model ?? "unknown",
    cli: first?.meta?.cli ?? "unknown",
    date: /(\d{4}-\d{2}-\d{2})(?:\/core)?$/.exec(dir)?.[1] ?? "not in the directory name",
    n: { bare: arm("bare").length, skill: arm("skill").length },
    rows: Object.keys(metrics).map((k) => metricRow(rows, k)),
    cost: { bare: cost("bare"), skill: cost("skill") },
    totalCostUsd: rows.map((r) => r.meta?.cost_usd).filter((x) => typeof x === "number").reduce((a, b) => a + b, 0),
    runs: rows.length,
  };
}

const fmt = (x) => (x === null ? "n/a" : (x >= 0 ? "+" : "") + x.toFixed(2));

export function render(summaries) {
  const out = [
    "# Results by model",
    "",
    "Generated by `node evals/by-model.mjs`. Each section is one model, run on the same eight tasks; the numbers are never averaged across models. The reading rule was written before any data was collected, in `evals/MODELS-DESIGN.md`: a metric `worked` when the 95% bootstrap interval of the mean per-task delta is entirely above zero, `worse` when it is entirely below, and `no clear effect` otherwise.",
    "",
    "The claude-opus-5 section below is the 17 October run. It replaced the 5 September table, which README.md no longer shows.",
    "",
  ];
  for (const s of summaries) {
    out.push(
      `## ${s.model}`,
      "",
      `Run ${s.date} with Claude Code ${s.cli}, results in \`${s.dir}\`. ${s.n.bare} bare runs and ${s.n.skill} skill runs.`,
      "",
      "| metric | bare | skill | mean delta per task | 95% interval | reading |",
      "|---|---:|---:|---:|---|---|",
    );
    for (const r of s.rows) out.push(`| ${r.title} | ${r.bare} / ${s.n.bare} | ${r.skill} / ${s.n.skill} | ${fmt(r.delta)} | ${r.low === null ? "n/a" : `${fmt(r.low)} to ${fmt(r.high)}`} | ${r.reading} |`);
    out.push("", `Mean cost per run: bare ${s.cost.bare === null ? "n/a" : `$${s.cost.bare.toFixed(2)}`}, skill ${s.cost.skill === null ? "n/a" : `$${s.cost.skill.toFixed(2)}`}. Total for the ${s.runs} runs in this directory: $${s.totalCostUsd.toFixed(2)}.`, "");
  }
  return out.join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const dirs = process.argv.slice(2).filter((a) => !a.startsWith("--"));
  if (!dirs.length) {
    console.error("usage: node evals/by-model.mjs <results-dir> [<results-dir> ...]");
    process.exit(2);
  }
  console.log(render(dirs.map(summarise)));
}
